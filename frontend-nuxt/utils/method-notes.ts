/**
 * Реестр методических пометок — места, где сервис выбрал одну трактовку из
 * нескольких, либо разошёлся с исходной версией коллеги.
 *
 * Единственный источник правды для интерфейса; текст здесь короткий, а полное
 * изложение с таблицами и цифрами — в `docs/ASTROLOGER-REVIEW.md` под теми же
 * идентификаторами (А1…А9 — открытые вопросы, Б1…Б6 — отличия от исходника).
 *
 * Правило: ничего не выдумываем. Если методика спорная — она помечена, а не
 * подана как канон. Снимать пометку можно только после ответа астролога.
 */

export type MethodNoteKind =
  /** Развилка школ: выбран рабочий вариант, решение за астрологом. */
  | 'ask'
  /** Метод конкретной школы, не общий канон. */
  | 'school'
  /** Сознательное отличие от исходной версии коллеги. */
  | 'diff'
  /** Данных или методики нет — сознательно не показываем. */
  | 'gap'

export interface MethodNote {
  /** Идентификатор из docs/ASTROLOGER-REVIEW.md: «А1», «Б2» и т.д. */
  id: string
  kind: MethodNoteKind
  /** Заголовок в одну строку — то, что видно в свёрнутом виде. */
  title: string
  /** Что именно сделано сейчас. */
  current: string
  /** Чего ждём от специалиста; пусто, если вопроса нет. */
  ask?: string
}

