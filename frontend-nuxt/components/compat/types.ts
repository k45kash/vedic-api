/** Дробные баллы (1,5 у тары, ½ у вашьи) — запятая, без хвостов «.0». */
export function fmtScore(v: number | null): string {
  if (v === null || v === undefined || !Number.isFinite(v)) return '—'
  return String(Math.round(v * 100) / 100).replace('.', ',')
}
