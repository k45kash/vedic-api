/** Откуда взята Луна человека. */
export type CompatSource =
  /** Постоянный профиль пользователя (useBirthProfile). */
  | 'profile'
  /** Данные рождения, введённые на этой странице → POST /api/horoscope. */
  | 'birth'
  /** Известна только накшатра — раши Луны нет, полный расчёт невозможен. */
  | 'nakshatra'

/** Один человек в паре, приведённый к тому, что нужно ашта-куте. */
export interface CompatPerson {
  /** Накшатра Луны, 1..27. */
  nakNo: number
  /** Знак Луны (раши), 1..12. null — известна только накшатра. */
  moonSign: number | null
  /** Градус Луны в знаке 0..30. Нужен Вашье: Стрелец и Козерог делятся пополам. */
  moonDeg: number | null
  source: CompatSource
  /** Строка «15 июня 1990, 14:30 · Москва» для подписи. Пусто в режиме накшатры. */
  birthLine: string
  /** Время рождения не указано — считали на полдень. */
  timeUnknown: boolean
  /** Знак Луны под вопросом: время неизвестно, Луна близко к границе знака. */
  moonSignUncertain: boolean
  /** Накшатра под вопросом: граница накшатры либо неизвестное время. */
  nakUncertain: boolean
}

