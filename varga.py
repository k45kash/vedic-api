NAVAMSA_SIZE = 360.0 / 108          # 3°20' — он же размер пады накшатры


def navamsa_index(lon: float) -> int:
    """Сквозной номер навамши 0..107 от 0° Овна.

    Это же — сквозной номер пады накшатры: 27 накшатр × 4 пады = 108 = 12 × 9,
    и границы совпадают точно (13°20' / 4 = 3°20'). Именно эта тождественность
    позволяет раскрасить круг 108 пад (`content/chart_geometry.json` →
    `pada_wheel`) знаками навамши.

    Совпадение с падой из `nakshatra_calculator.get_nk` закреплено тестом —
    там пада считается двумя делениями подряд, здесь одним, и на границе
    отрезков арифметика с плавающей точкой могла бы разойтись.

    Собирается из номера знака и номера части внутри него, а не отдельным
    делением: так сквозной номер по построению согласован с `varga_sign`
    (см. заметку о float в `varga_part`).
    """
    return (_sign_of(lon) - 1) * 9 + varga_part(lon, 9)


def navamsa(lon: float) -> dict:
    """Полная позиция в навамше (D9) по сидерической долготе.

    Схема отсчёта — правило Парашары (подвижный от себя, неподвижный от 9-го,
    двойственный от 5-го); обоснование и эквивалентность непрерывному счёту
    разобраны в docstring модуля.

    ── Контрольные карты ─────────────────────────────────────────────────
    Карта A — 15.06.1990 14:30, Москва (55.7558 N, 37.6173 E), UTC+4 (MSD).
    Карта B — 01.11.1985 08:00, Мумбаи (19.08 N, 72.88 E), UTC+5:30 (IST).
    Знаки D9 по девяти планетам и лагне зафиксированы эталонами в
    `tests/test_varga.py`. Карта A выбрана так, что лагна D1 (Дева) и лагна
    D9 (Овен) различаются, — на ней сразу видно подмену системы домов; на
    ней же единственная варготтама (Сатурн в Козероге 0°18').

    Если знак D9 разошёлся с внешним калькулятором — сначала сверяй D1.
    Схема отсчёта у всех программ одна (разбор в docstring модуля), а вот
    аянамша, часовой пояс и округление легко сдвигают долготу через границу
    3°20'; у карты A Сатурн стоит в 18' от начала знака, то есть ровно в
    такой зоне риска.

    Возвращает номер и название знака, номер навамши внутри знака (1..9),
    сквозной номер 0..107, градус внутри знака навамши и флаг варготтамы.
    """
    sign_num = _sign_of(lon)
    part = varga_part(lon, 9)                      # 0..8
    nav_sign = varga_sign(lon, 9)
    sg = SIGNS[nav_sign - 1]

    # Градус внутри знака навамши: отрезок 3°20' растягивается на все 30°.
    # Смещение берём от начала СВОЕЙ навамши (через её сквозной номер), а не
    # остатком от деления — см. заметку о float в `varga_part`.
    idx = navamsa_index(lon)
    frac = min(max(((lon % 360) - idx * NAVAMSA_SIZE) / NAVAMSA_SIZE, 0.0), 1.0)
    return {
        "sign_num":     nav_sign,
        "sign":         sg["name"],
        "sign_ru":      sg["ru"],
        "lord":         sg["lord"],
        "navamsa":      part + 1,                  # 1..9 внутри знака D1
        "navamsa_abs":  idx,                       # 0..107, он же номер пады
        "deg_in_sign":  round(frac * 30, 6),
        "vargottama":   nav_sign == sign_num,
        "d1_sign_num":  sign_num,
        "d1_sign_ru":   SIGNS[sign_num - 1]["ru"],
    }


def is_vargottama(lon: float) -> bool:
    """Варготтама — планета в ОДНОМ И ТОМ ЖЕ знаке в D1 и D9.

    Классический признак силы: планета «пришедшая в лучшую варгу» держит
    свой знак и в раши, и в навамше, поэтому обещанное ею не размывается.

    Источник. В BPHS термин определён только для лагны и мимоходом — гл. 46,
    шлоки 32–34 (в разделе шатабдика-даши): асцендент варготтамный, когда
    знак лагны в раши и в навамше один. Общее определение для планеты берём
    из «Пхаладипики» Мантрешвары, гл. 3, где варготтамой названа та навамша
    знака, которая несёт этот же знак; там же варготтама стоит в списке
    условий силы планеты. То же определение — у P.V.R. Narasimha Rao
    (учебник, сноска 40).

    При правиле Парашары это условие выполняется ровно в трёх случаях:
      • 1-я навамша подвижного знака   (0°00'–3°20')
      • 5-я навамша неподвижного знака (13°20'–16°40')
      • 9-я навамша двойственного знака (26°40'–30°00')
    То есть на любой знак приходится ровно одна варготтамная навамша, а на
    весь круг — 12 из 108 (11,1%). Эквивалентность закреплена тестом.

    Терминологическая осторожность: словом «варготтама» иногда называют
    совпадение знака в D1 и ЛЮБОЙ другой варге. Здесь — только D1/D9,
    как в классическом определении; если понадобится обобщение, оно
    делается через `same_sign_in(lon, varga)`, а не переопределением этого.
    """
    return varga_sign(lon, 9) == _sign_of(lon)


def same_sign_in(lon: float, varga: int) -> bool:
    """Совпадает ли знак варги D<varga> со знаком раши D1.

    Обобщение варготтамы на прочие вибхаги — отдельной функцией, чтобы
    классический термин не размывался (см. `is_vargottama`).
    """
    return varga_sign(lon, varga) == _sign_of(lon)


