def varga_position(lon: float, varga: int) -> dict:
    """Позиция одной точки в одной варге — единый формат для всех вибхаг."""
    if varga == 2:
        h = hora(lon)
        return {
            "varga":     "D2",
            "sign_num":  h["sign_num"],
            "sign":      h["sign"],
            "sign_ru":   h["sign_ru"],
            "lord":      h["ruler"],
            "part":      h["half"],
            "parts":     2,
            "same_as_d1": h["sign_num"] == _sign_of(lon),
        }
    spec = VARGA_SPECS.get(varga)
    if spec is None:
        raise ValueError(
            f"варга D{varga} не поддерживается; есть {', '.join(SUPPORTED)}"
        )
    sn = varga_sign(lon, varga)
    sg = SIGNS[sn - 1]
    return {
        "varga":     spec["code"],
        "sign_num":  sn,
        "sign":      sg["name"],
        "sign_ru":   sg["ru"],
        "lord":      sg["lord"],
        "part":      varga_part(lon, spec["divisions"]) + 1,
        "parts":     spec["divisions"],
        "same_as_d1": sn == _sign_of(lon),
    }


def navamsa_chart(planets: Sequence[dict], lagna_sid: float) -> dict:
    """Компактная карта навамши D9 — та, что едет вместе с гороскопом.

    `planets` — список словарей в формате `nakshatra_calculator.get_planet_positions`
    (нужны только ключи `name` и `sid`). `lagna_sid` — сидерическая долгота
    асцендента.

    **Состав выбран по принципу «только невыводимое».** `/api/horoscope` и без
    того около 9 КБ, поэтому здесь нет ничего, что клиент получает даром:
      • владелец знака — таблица из 12 строк, она у фронта есть;
      • список 12 домов — Whole Sign от `lagna.sign_num`, чистая арифметика;
      • знак D1 планеты — он в этом же ответе, в `planets`.
    Полная карта D9 со знаками, владельцами и домами — в `/api/varga`.
    Такой состав держит блок в пределах ~1,2 КБ вместо 3,8 КБ.

    Дома планет всё же считаются здесь: без них фронту пришлось бы знать,
    что дома навамши берутся Whole Sign ОТ НАВАМША-ЛАГНЫ, а не от лагны D1 —
    это методическое знание, а не арифметика, и место ему в ядре.
    """
    lg = navamsa(lagna_sid)
    lagna_sign = lg["sign_num"]

    out_planets = []
    for p in planets:
        n = navamsa(p["sid"])
        out_planets.append({
            "name":       p["name"],
            "sign_num":   n["sign_num"],
            "sign_ru":    n["sign_ru"],
            "pada_abs":   n["navamsa_abs"],
            "house":      ((n["sign_num"] - lagna_sign) % 12) + 1,
            "vargottama": n["vargottama"],
        })

    return {
        "varga":   "D9",
        "name_ru": "Навамша",
        "scheme":  "Парашара: подвижный знак — от себя, неподвижный — от 9-го, "
                   "двойственный — от 5-го",
        "houses":  "whole-sign от навамша-лагны",
        "lagna": {
            "sign_num":   lg["sign_num"],
            "sign_ru":    lg["sign_ru"],
            "pada_abs":   lg["navamsa_abs"],
            "vargottama": lg["vargottama"],
        },
        "planets":    out_planets,
        "vargottama": [p["name"] for p in out_planets if p["vargottama"]]
                      + (["Лагна"] if lg["vargottama"] else []),
    }


def calc_vargas(planets: Sequence[dict], lagna_sid: float,
                vargas: Optional[Sequence[int]] = None) -> dict:
    """Набор дивизиональных карт для планет и лагны.

    `vargas` — список номеров (по умолчанию все поддерживаемые: 1, 2, 3, 7,
    9, 10, 12). Для каждой варги возвращается лагна, планеты и дома
    (Whole Sign от лагны этой варги).

    D2 (хора) дома не получает: её «карта» состоит всего из двух знаков —
    Лев и Рак, — и раскладка по 12 домам для неё бессмысленна.
    """
    if vargas is None:
        vargas = [1, 2, 3, 7, 9, 10, 12]

    charts = {}
    for v in vargas:
        if v != 2 and v not in VARGA_SPECS:
            raise ValueError(
                f"варга D{v} не поддерживается; есть {', '.join(SUPPORTED)}"
            )
        spec = HORA_SPEC if v == 2 else VARGA_SPECS[v]
        lg = varga_position(lagna_sid, v)
        lagna_sign = lg["sign_num"]

        items = []
        for p in planets:
            pos = varga_position(p["sid"], v)
            items.append({
                **pos,
                "name":  p["name"],
                "abbr":  p.get("abbr"),
                # У хоры дома нет: два знака на всю карту, номер дома в ней
                # не значит ничего.
                "house": None if v == 2
                         else ((pos["sign_num"] - lagna_sign) % 12) + 1,
            })

        chart = {
            "code":    spec["code"],
            "name":    spec["name"],
            "name_ru": spec["ru"],
            "means":   spec["means"],
            "source":  spec["source"],
            "lagna":   lg,
            "planets": items,
        }
        # У хоры (и только у неё) «общепринятый вариант» реально спорен —
        # называем выбранную схему явно, в духе реестра пометок методики
        # (`frontend-nuxt/utils/method-notes.ts`).
        if "scheme" in spec:
            chart["scheme"] = spec["scheme"]
        if v != 2:
            chart["houses"] = [
                {"house": i + 1,
                 "sign_num": ((lagna_sign - 1 + i) % 12) + 1,
                 "sign_ru": SIGNS[((lagna_sign - 1 + i) % 12)]["ru"]}
                for i in range(12)
            ]
        charts[spec["code"]] = chart

    return {
        "charts": charts,
        "vargottama": {
            "definition": "планета в одном и том же знаке в D1 и D9",
            "planets": [p["name"] for p in planets if is_vargottama(p["sid"])],
            "lagna":   is_vargottama(lagna_sid),
        },
    }


