def varga_part(lon: float, divisions: int) -> int:
    """Номер части внутри знака, 0-базовый: 0..divisions-1.

    ── Про арифметику с плавающей точкой (не косметика) ──────────────────
    Наивное `int(градус_в_знаке / (30 / divisions))` разъезжается с
    `int(долгота / (360 / (12 × divisions)))` ровно на границах отрезков:
    ни 30/9, ни 360/108 не представимы в double точно, и деление
    округляется в разные стороны. На круге при шаге 0.033° таких точек
    семь — 56.666666666666664 (26°40' Тельца) и ещё шесть.

    Поэтому считаем **умножением, а не делением на дробный шаг**:
        сквозной номер = int(долгота × divisions / 30)
    Умножение на целое `divisions` до деления убирает вторую операцию
    округления, и оба пути дают один ответ. Результат дополнительно зажат
    в диапазон и привязан к номеру знака из `_sign_of`, чтобы часть и знак
    не могли рассогласоваться даже теоретически.

    Полное совпадение с падой из `nakshatra_calculator.get_nk` проверяется
    тестом `test_navamsa_index_matches_pada`.
    """
    idx = _part_index(lon, 12 * divisions)      # сквозной номер части 0..12·divisions-1
    return idx % divisions


def varga_sign(lon: float, varga: int) -> int:
    """Сидерическая долгота → номер знака (1..12) в варге D<varga>.

    Поддерживаются варги из `VARGA_SPECS` (1, 3, 7, 9, 10, 12).
    Хора (D2) считается функцией `hora()` — у неё другое правило.
    """
    if varga == 2:
        return hora(lon)["sign_num"]
    spec = VARGA_SPECS.get(varga)
    if spec is None:
        raise ValueError(
            f"варга D{varga} не поддерживается; есть {', '.join(SUPPORTED)}"
        )
    sign_num = _sign_of(lon)
    part = varga_part(lon, spec["divisions"])
    start0 = (sign_num - 1 + spec["start"](sign_num)) % 12
    return (start0 + part * spec["step"]) % 12 + 1


def hora(lon: float) -> dict:
    """D2, хора — половина знака (15°). Правило Парашары.

    В НЕЧЁТНОМ знаке (Овен, Близнецы, …) первая половина принадлежит хоре
    Солнца (знак Лев), вторая — хоре Луны (знак Рак). В ЧЁТНОМ знаке
    (Телец, Рак, …) порядок обратный.

    В отличие от прочих варг, D2 отображает знак не на последовательность
    из 12 знаков, а всего на два — Лев и Рак. Поэтому «карта D2» состоит
    ровно из двух занятых знаков, и это норма, а не дефект расчёта.
    """
    sign_num = _sign_of(lon)
    half = varga_part(lon, 2)              # 0 — первая половина, 1 — вторая
    odd = sign_num % 2 == 1
    is_sun = (half == 0) if odd else (half == 1)
    return {
        "sign_num": 5 if is_sun else 4,    # Лев / Рак
        "sign": "Leo" if is_sun else "Cancer",
        "sign_ru": "Лев" if is_sun else "Рак",
        "ruler": "Солнце" if is_sun else "Луна",
        "half": half + 1,
    }


