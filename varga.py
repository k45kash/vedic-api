def _print_chart(res: dict) -> None:
    d9 = res["charts"]["D9"]
    print(f"\n  ── {d9['name_ru']} ({d9['code']}) ──────────────────────────")
    lg = d9["lagna"]
    mark = "  ⟵ ВАРГОТТАМА" if lg["same_as_d1"] else ""
    print(f"  {'Лагна':<12}{lg['sign_ru']:<12}{mark}")
    for p in d9["planets"]:
        mark = "  ⟵ ВАРГОТТАМА" if p["same_as_d1"] else ""
        print(f"  {p['name']:<12}{p['sign_ru']:<12}дом {p['house']:<4}{mark}")


def _selftest() -> None:
    """Быстрая проверка инвариантов без pytest — полные тесты в tests/test_varga.py."""
    assert varga_sign(0.0, 9) == 1, "0° Овна → навамша Овен"
    assert varga_sign(29.99, 9) == 9, "конец Овна → 9-я навамша, Стрелец"
    assert varga_sign(30.0, 9) == 10, "0° Тельца → навамша Козерог (9-й от Тельца)"
    assert varga_sign(60.0, 9) == 7, "0° Близнецов → навамша Весы (5-й от Близнецов)"
    assert varga_sign(90.0, 9) == 4, "0° Рака → навамша Рак (подвижный, от себя)"
    # Эквивалентность правила Парашары непрерывному счёту — на всём круге
    for i in range(10800):
        lon = i / 30.0
        assert varga_sign(lon, 9) == navamsa_index(lon) % 12 + 1, lon
    assert sum(1 for p in pada_wheel() if p["vargottama"]) == 12
    print("selftest: OK")


