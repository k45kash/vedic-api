def pada_wheel() -> List[dict]:
    """Статическая таблица 108 пад → знак навамши.

    Ни от даты, ни от места не зависит: это разбиение самого зодиака.
    Нужна кругу пад из `content/chart_geometry.json` → `pada_wheel`, где
    у варготтамных секторов своя непрозрачность (`fill_opacity.pada_vargottama`).

    Каждый элемент: сквозной номер пады 0..107, накшатра 1..27, пада 1..4,
    знак раши, знак навамши и флаг варготтамы (знаки совпали).
    """
    out = []
    for i in range(108):
        lon = i * NAVAMSA_SIZE            # начало отрезка — середина не нужна,
        mid = lon + NAVAMSA_SIZE / 2      # но берём середину, чтобы уйти от границы
        d1 = _sign_of(mid)
        d9 = varga_sign(mid, 9)
        out.append({
            "index":      i,
            "start_deg":  round(lon, 6),
            "nakshatra":  i // 4 + 1,
            "pada":       i % 4 + 1,
            "d1_sign":    d1,
            "d1_sign_ru": SIGNS[d1 - 1]["ru"],
            "d9_sign":    d9,
            "d9_sign_ru": SIGNS[d9 - 1]["ru"],
            "vargottama": d1 == d9,
        })
    return out


