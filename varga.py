def _part_index(lon: float, parts_on_circle: int) -> int:
    """Номер части круга, 0-базовый, при делении круга на `parts_on_circle`.

    Через точную дробную арифметику — так же, как `utils.global_pada`, и это
    не педантизм. Прежний вариант («умножить до деления») чинил основную беду,
    но на проверке в 10 тысяч точек всё равно расходился с точным ответом в
    23 из них — и в результате `varga.navamsa_index` и
    `nakshatra_calculator.get_nk` давали РАЗНЫЕ пады для одной и той же
    долготы на 32 точках. Два модуля, спорящих о номере пады, — ровно тот
    класс дефекта, ради которого заводились тесты.

    `Fraction(float)` представляет double как точную дробь, поэтому ответ
    перестаёт зависеть от порядка операций. Цена — единицы микросекунд.
    """
    return int(Fraction(lon) % 360 // Fraction(360, parts_on_circle))


def _sign_of(lon: float) -> int:
    """Сидерическая долгота → номер знака 1..12."""
    return _part_index(lon, 12) + 1


