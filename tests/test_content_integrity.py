# 27 накшатр разбиты на девять троек, и тройки чередуются:
#   Ади-Мадхья-Антья, Антья-Мадхья-Ади, Ади-Мадхья-Антья, …
# Это и есть эталон, которым проверялось поле `dosha` при разборе дефекта.
ВПЕРЁД = ["Ади", "Мадхья", "Антья"]
DOSHA_TO_NADI = {"Вата": "Ади", "Питта": "Мадхья", "Капха": "Антья"}

# Девять накшатр, у которых проза `compat` расходится со структурным полем
# (пункт А1 листа для астролога). Список именно такой — ни больше ни меньше.
ПРОЗА_ВРЁТ = {5, 6, 8, 9, 10, 12, 16, 21, 25}

# Четыре позиции, где расходятся названия накшатр в API и в контенте.
# Расхождение известное и обойдено сопоставлением по номеру — фиксируем его
# ровно в этих четырёх местах, чтобы тест упал, если разъедется что-то ещё.
ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ_ИМЁН = {
    20: ("Пурвашадха", "Пурва Ашадха"),
    21: ("Уттарашадха", "Уттара Ашадха"),
    25: ("Пурвабхадра", "Пурва Бхадрапада"),
    26: ("Уттарабхадра", "Уттара Бхадрапада"),
}


def канон_нади(no: int) -> str:
    """Нади n-й накшатры (1..27) по канонической схеме троек."""
    тройка, место = divmod(no - 1, 3)
    ряд = ВПЕРЁД if тройка % 2 == 0 else list(reversed(ВПЕРЁД))
    return ряд[место]


