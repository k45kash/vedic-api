def test_доша_совпадает_с_канонической_схемой_нади(накшатры):
    """Эталон: Ади-Мадхья-Антья / Антья-Мадхья-Ади по тройкам.

    Это и было основанием выбрать `dosha` источником нади вместо прозы —
    структурное поле верно на все 27 позиций.
    """
    расхождения = [
        (n["no"], n["name"], DOSHA_TO_NADI[n["dosha"]], канон_нади(n["no"]))
        for n in накшатры
        if DOSHA_TO_NADI[n["dosha"]] != канон_нади(n["no"])
    ]
    assert not расхождения, расхождения


def test_проза_расходится_ровно_у_девяти_накшатр(накшатры):
    """Свободный текст `compat` врёт у девяти — фиксируем поимённо.

    Тест сторожит обе стороны: если коллега поправит прозу, список сократится
    и тест упадёт — это хороший повод перепроверить, а не тихо разъехаться.
    """
    import re

    врут = set()
    for n in накшатры:
        m = re.search(r"Нади\s*[—-]\s*([А-Яа-я/]+)", n.get("compat", ""))
        if not m:
            continue
        сырое = m.group(1)
        из_прозы = ("Антья" if ("Антья" in сырое or "Анта" in сырое)
                    else "Мадхья" if "Мадхья" in сырое
                    else "Ади" if "Ади" in сырое else сырое)
        if из_прозы != канон_нади(n["no"]):
            врут.add(n["no"])

    assert врут == ПРОЗА_ВРЁТ, (
        f"ожидали расхождение прозы у {sorted(ПРОЗА_ВРЁТ)}, получили {sorted(врут)}"
    )


