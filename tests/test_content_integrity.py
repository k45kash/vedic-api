@pytest.mark.parametrize("файл", sorted(ПОЛЯ_ЭЛЕМЕНТОВ))
def test_поля_элементов_есть_у_каждой_записи(файл, контент):
    """Отсутствие поля у одной записи из 27 — самый тихий вид дефекта.

    Именно так терялась нади: `compat` есть у всех, но содержимое врало.
    Здесь проверяется хотя бы наличие всех полей, по которым идёт чтение.
    """
    раздел, поля = ПОЛЯ_ЭЛЕМЕНТОВ[файл]
    d = контент(файл)
    записи = d if раздел is None else d[раздел]
    for i, з in enumerate(записи):
        отсутствуют = [p for p in поля if p not in з]
        assert not отсутствуют, f"{файл}[{i}]: нет полей {отсутствуют}"


