def test_словесных_записей_титх_ровно_42(контент):
    """Столько записей справочника терялось на `parseInt`. Считаем заново.

    Считаем по тому же признаку, что и сломанный код: `parseInt` не смог
    прочитать число. Число 42 — не снимок текущего вывода, а объём проблемы,
    зафиксированный при разборе дефекта.
    """
    события = контент("events_muhurta.json")["events"]
    словом = []
    for e in события:
        for ключ in ("good_tithis", "avoid_tithis"):
            for x in e.get(ключ) or []:
                s = str(x).strip()
                # аналог parseInt: число, если строка НАЧИНАЕТСЯ с цифр
                if not s[:1].isdigit():
                    словом.append((e["id"], ключ, s))
    assert len(словом) == 42, словом

    словарь = [s for _, _, s in словом]
    амавасья = [s for s in словарь if "амавас" in s.lower()]
    пурнима = [s for s in словарь if "пурним" in s.lower()]
    # 32 + 8 = 40 из 42 — это и есть «две самые значимые титхи»
    assert (len(амавасья), len(пурнима)) == (32, 8)

    # Оставшиеся две записи — категории, а не титхи: «рикта» и
    # «Нанда-титхи 1,6,11 (для благих дел)». Они тоже терялись, пока сверка
    # не научилась разворачивать категорию через поле `cat` из tithi.json
    # (см. следующий тест).
    прочее = [s for s in словарь if "амавас" not in s.lower() and "пурним" not in s.lower()]
    assert len(прочее) == 2, прочее


def test_категории_титх_разворачиваются_в_номера(tmp_path):
    """Записи-категории («рикта», «Нанда-титхи …») должны влиять на оценку.

    Состав категорий берётся из поля `cat` в `tithi.json`, а не из таблицы в
    коде: Рикта — 4, 9, 14; Нанда — 1, 6, 11.

    У события «Разрешение споров» Нанда-титхи стоят в `avoid_tithis`, а
    Чатурдаши (14) — наоборот в `good_tithis`, «сильна для устранения».
    Накшатра подбирается так, чтобы событие не было заветировано, — тогда
    титхи остаётся единственной переменной.
    """
    res = run_ts("""
    const m = await import(FE + 'calculators/event-picker.ts')
    const события = await m.listEvents()
    const споры = события.find(e => /Разрешение споров/.test(e.name))
    let накшатра = null
    for (let n = 1; n <= 27; n++) {
      const r = m.scoreEvent({ eventId: споры.id, dayNakNo: n, weekday: 'Среда', janmaNo: 5, tithi: 2, paksha: 'shukla' })
      if (r && r.pct > 0) { накшатра = n; break }
    }
    const оценка = (tithi) => m.scoreEvent({ eventId: споры.id, dayNakNo: накшатра, weekday: 'Среда', janmaNo: 5, tithi, paksha: 'shukla' }).pct
    out({ нанда: [1, 6, 11].map(оценка), нейтральные: [2, 5].map(оценка), чатурдаши: оценка(14) })
    """, tmp_path)

    нейтральная = res["нейтральные"][0]
    assert res["нейтральные"] == [нейтральная, нейтральная]
    # Нанда-титхи в списке избегаемых — оценка обязана просесть
    assert all(x < нейтральная for x in res["нанда"]), res
    # Чатурдаши в списке хороших — наоборот, выше нейтральной
    assert res["чатурдаши"] > нейтральная, res


def test_амавасья_и_пурнима_распознаются_подбором_события(tmp_path):
    """Регрессия дефекта №2: стрижка на Амавасью обязана падать в оценке.

    У события `haircut` Амавасья и Пурнима стоят в `avoid_tithis`, а титхи
    здесь единственная переменная — накшатра, день недели и йога не подаются.
    Раньше словесная запись отбрасывалась, и день получал «отличное окно»
    ровно там, где справочник предостерегает.
    """
    res = run_ts("""
    const { scoreEvent } = await import(FE + 'calculators/event-picker.ts')
    // Прочие факторы зафиксированы, титхи — единственная переменная
    const базa = { eventId: 'haircut', janmaNo: 5, dayNakNo: 22, weekday: 'Пятница' }
    const оценка = (tithi, paksha) => {
      const r = scoreEvent({ ...базa, tithi, paksha })
      return { pct: r.pct, gained: r.gained, total: r.total }
    }
    out({
      амавасья: оценка(15, 'krishna'),
      пурнима:  оценка(15, 'shukla'),
      хорошая:  оценка(5, 'shukla'),
      нейтральная: оценка(12, 'shukla'),
    })
    """, tmp_path)

    вес_титхи = 2   # picker_weights.json
    # Нейтральная титхи не в списках — ни плюса, ни минуса.
    # Амавасья и Пурнима стоят в avoid_tithis, значит ровно −2 к нейтральной.
    assert res["хорошая"]["gained"] - res["нейтральная"]["gained"] == вес_титхи
    assert res["нейтральная"]["gained"] - res["амавасья"]["gained"] == вес_титхи
    assert res["нейтральная"]["gained"] - res["пурнима"]["gained"] == вес_титхи
    # Амавасья и Пурнима — одна и та же 15-я титхи, различает их только пакша
    assert res["амавасья"] == res["пурнима"]


