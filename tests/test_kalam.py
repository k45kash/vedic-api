"""Раху-калам, Гулика-калам, Ямаганда-калам.

Метод (пункт А4 листа для астролога): светлое время суток делится на восемь
равных частей, номер части задаётся днём недели. Расчёт живёт в
`frontend-nuxt/utils/kalam.ts`, поэтому тесты исполняют настоящий TypeScript
через мостик, а не пересказывают его логику.

Эталон здесь один и внешний — опубликованная таблица Prokerala для
«идеального» дня 6:00–18:00, при котором часть равна ровно 1 ч 30 мин. Она же
процитирована в шапке kalam.ts. Всё остальное — инварианты: восемь равных
частей, сумма, непересечение трёх периодов, попадание внутрь светлого времени.
"""

import json
from datetime import date, timedelta

import pytest

from tests._ts_bridge import run_ts
from Panchangam import calc_panchang

# ── Эталон Prokerala: Раху-калам при восходе 6:00 и закате 18:00 ───────────
# https://www.prokerala.com/astrology/rahukalam/
# Ключ — день недели по Date.getDay() (0 = воскресенье).
РАХУ_ЭТАЛОН = {
    0: ("16:30", "18:00"),   # Вс — 8-я часть
    1: ("07:30", "09:00"),   # Пн — 2-я
    2: ("15:00", "16:30"),   # Вт — 7-я
    3: ("12:00", "13:30"),   # Ср — 5-я
    4: ("13:30", "15:00"),   # Чт — 6-я
    5: ("10:30", "12:00"),   # Пт — 4-я
    6: ("09:00", "10:30"),   # Сб — 3-я
}

# AnytimeAstro, вторник: Ямагандам 09:00–10:30 (3-я), Гулика 12:00–13:30 (5-я).
# https://www.anytimeastro.com/blog/astrology/tuesday-rahukalam-and-yamagandam-time/
ВТОРНИК_ЭТАЛОН = {"yamaganda": ("09:00", "10:30"), "gulika": ("12:00", "13:30")}

# Неделя июля 2026: 26-е — воскресенье, дальше по кругу до субботы.
НЕДЕЛЯ = [date(2026, 7, 26) + timedelta(days=i) for i in range(7)]

СКРИПТ_ИДЕАЛЬНЫЙ_ДЕНЬ = """
    const { dayKalams } = await import(FE + 'utils/kalam.ts')
    const дни = %s
    const hhmm = (d) => String(d.getHours()).padStart(2, '0') + ':' + String(d.getMinutes()).padStart(2, '0')
    out(дни.map(([y, m, d]) => {
      const sr = new Date(y, m - 1, d, 6, 0, 0)
      const ss = new Date(y, m - 1, d, 18, 0, 0)
      return {
        weekday: sr.getDay(),
        periods: dayKalams(sr, ss).map((p) => ({
          key: p.key, part: p.part,
          start: hhmm(p.start), end: hhmm(p.end),
          ms: p.end.getTime() - p.start.getTime(),
          from_sunrise_ms: p.start.getTime() - sr.getTime(),
        })),
      }
    }))
"""


@pytest.fixture(scope="module")
def идеальный_день(tmp_path_factory):
    """Раскладка каламов для «книжного» дня 6:00–18:00 на всю неделю."""
    дни = [[d.year, d.month, d.day] for d in НЕДЕЛЯ]
    данные = run_ts(СКРИПТ_ИДЕАЛЬНЫЙ_ДЕНЬ % дни, tmp_path_factory.mktemp("kalam"))
    return {д["weekday"]: д["periods"] for д in данные}


def _по_ключу(периоды, key):
    (p,) = [x for x in периоды if x["key"] == key]
    return p


# ═══════════════════════════════════════════════════════════════════════
#  Эталон: опубликованные таблицы
# ═══════════════════════════════════════════════════════════════════════


@pytest.mark.parametrize("wd", range(7))
def test_раху_калам_совпадает_с_таблицей_prokerala(wd, идеальный_день):
    """Внешний эталон на весь недельный цикл, а не на один день.

    При восходе 6:00 и закате 18:00 часть равна 1 ч 30 мин, поэтому таблицу
    можно сверять по часам напрямую — без плавающих границ реального дня.
    """
    p = _по_ключу(идеальный_день[wd], "rahu")
    assert (p["start"], p["end"]) == РАХУ_ЭТАЛОН[wd], f"день недели {wd}"


def test_гулика_и_ямаганда_вторника_совпадают_с_публикацией(идеальный_день):
    """Второй независимый источник — на нём же сверялся автор kalam.ts."""
    вторник = идеальный_день[2]
    for key, (s, e) in ВТОРНИК_ЭТАЛОН.items():
        p = _по_ключу(вторник, key)
        assert (p["start"], p["end"]) == (s, e), key


def test_гулика_отсчитывается_обратно_от_субботы(идеальный_день):
    """Схема Гулики: суббота — 1-я часть, пятница 2-я … воскресенье 7-я.

    Правило простое и проверяемое формулой, а не таблицей: часть = 7 − wd + 1
    при отсчёте от субботы. Ловит перестановку строк в таблице.
    """
    ожидаемо = {6: 1, 5: 2, 4: 3, 3: 4, 2: 5, 1: 6, 0: 7}   # Сб…Вс
    for wd, часть in ожидаемо.items():
        assert _по_ключу(идеальный_день[wd], "gulika")["part"] == часть, wd


def test_номера_частей_это_перестановка_восьмёрки(идеальный_день):
    """Раху за неделю занимает семь РАЗНЫХ частей — повтор означал бы опечатку.

    Тот же контроль для Гулики (1..7) и Ямаганды (1..7): каждая схема обязана
    покрывать свои номера ровно по разу.
    """
    for key, диапазон in (("rahu", None), ("gulika", set(range(1, 8))),
                          ("yamaganda", set(range(1, 8)))):
        части = [_по_ключу(идеальный_день[wd], key)["part"] for wd in range(7)]
        assert len(set(части)) == 7, f"{key}: {части}"
        assert all(1 <= c <= 8 for c in части), f"{key}: {части}"
        if диапазон:
            assert set(части) == диапазон, f"{key}: {части}"


