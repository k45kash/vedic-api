@pytest.mark.parametrize("wd", range(7))
def test_восемь_равных_частей_светлого_дня(wd, идеальный_день):
    """Длительность каждого калама = светлый день / 8 = 1.5 ч ровно.

    Это и есть весь метод; если однажды часть станет 1/8 суток или 1/8 от
    восхода до восхода, тест это увидит.
    """
    for p in идеальный_день[wd]:
        assert p["ms"] == 12 * 3600 * 1000 // 8, p["key"]


@pytest.mark.parametrize("wd", range(7))
def test_начало_кратно_части_и_согласовано_с_номером(wd, идеальный_день):
    """Начало n-й части = восход + (n−1) × часть. Связка номера и времени.

    Без неё таблица номеров и таблица времён могли бы разъехаться незаметно.
    """
    часть = 12 * 3600 * 1000 // 8
    for p in идеальный_день[wd]:
        assert p["from_sunrise_ms"] == (p["part"] - 1) * часть, p["key"]


@pytest.mark.parametrize("wd", range(7))
def test_три_калама_не_пересекаются(wd, идеальный_день):
    """Раху, Гулика и Ямаганда всегда занимают разные части суток.

    Пересечение означало бы, что две схемы совпали на каком-то дне недели —
    традиция такого не даёт, и UI показал бы два стоп-фактора «в одном месте».
    """
    части = sorted(p["part"] for p in идеальный_день[wd])
    assert len(set(части)) == 3, части


@pytest.mark.parametrize("wd", range(7))
def test_каламы_внутри_светлого_времени(wd, идеальный_день):
    """Ни один калам не выходит за восход/закат — считается только дневная схема."""
    for p in идеальный_день[wd]:
        assert 0 <= p["from_sunrise_ms"], p["key"]
        assert p["from_sunrise_ms"] + p["ms"] <= 12 * 3600 * 1000, p["key"]


def test_три_периода_и_порядок_вывода(идеальный_день):
    """Ровно три стоп-фактора, Раху первым — так задан порядок вывода."""
    for wd in range(7):
        ключи = [p["key"] for p in идеальный_день[wd]]
        assert ключи == ["rahu", "gulika", "yamaganda"], wd


