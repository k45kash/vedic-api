@pytest.fixture(scope="module")
def реальный_день(tmp_path_factory):
    """Каламы на настоящих восходах/закатах Москвы — как их отдаёт /api/panchang.

    Летний московский день длиннее 16 часов, поэтому часть выходит около двух
    часов — деление на 8 не должно от этого поплыть.
    """
    п = calc_panchang(date(2026, 6, 20), date(2026, 6, 26), 3.0, 55.7558, 37.6173)
    дни = [[d["dt_sunrise"].isoformat(), d["dt_sunset"].isoformat()] for d in п["days"]]
    скрипт = """
    const { dayKalams } = await import(FE + 'utils/kalam.ts')
    out(%s.map(([a, b]) => {
      const sr = new Date(a), ss = new Date(b)
      return {
        weekday: sr.getDay(),
        day_ms: ss.getTime() - sr.getTime(),
        periods: dayKalams(sr, ss).map((p) => ({
          key: p.key, part: p.part, ms: p.end.getTime() - p.start.getTime(),
          from_sunrise_ms: p.start.getTime() - sr.getTime(),
        })),
      }
    }))
    """ % json.dumps(дни)
    return run_ts(скрипт, tmp_path_factory.mktemp("kalam-real"))


def test_на_реальных_восходах_часть_остаётся_восьмой(реальный_день):
    """Светлый день из Panchangam делится на 8 — при любой его длине."""
    assert len(реальный_день) == 7
    for д in реальный_день:
        assert д["day_ms"] > 16 * 3600 * 1000, "июнь в Москве — день длиннее 16 ч"
        for p in д["periods"]:
            assert abs(p["ms"] - д["day_ms"] / 8) <= 1, p["key"]


def test_на_реальных_восходах_суммы_и_границы(реальный_день):
    """Три периода в сумме — ровно 3/8 светлого дня, и все внутри него."""
    for д in реальный_день:
        сумма = sum(p["ms"] for p in д["periods"])
        assert abs(сумма - 3 * д["day_ms"] / 8) <= 3
        for p in д["periods"]:
            assert 0 <= p["from_sunrise_ms"]
            assert p["from_sunrise_ms"] + p["ms"] <= д["day_ms"] + 1


def test_номер_части_зависит_только_от_дня_недели(реальный_день, идеальный_день):
    """Реальный день и «книжный» 6:00–18:00 обязаны дать одинаковые НОМЕРА.

    Времена, конечно, разные — но метод берёт номер исключительно из дня
    недели, и это надо зафиксировать: подмешивание широты или даты в выбор
    части была бы тихой ошибкой.
    """
    for д in реальный_день:
        реальные = {p["key"]: p["part"] for p in д["periods"]}
        книжные = {p["key"]: p["part"] for p in идеальный_день[д["weekday"]]}
        assert реальные == книжные, д["weekday"]


def test_некорректный_интервал_даёт_пустой_список(tmp_path):
    """Закат раньше восхода (полярная ночь, битые данные) — не считаем ничего.

    Молчаливый расчёт «наоборот» выдал бы каламы с отрицательной длиной.
    """
    res = run_ts("""
    const { dayKalams } = await import(FE + 'utils/kalam.ts')
    const d = (h) => new Date(2026, 6, 26, h, 0, 0)
    out({
      обратный: dayKalams(d(18), d(6)).length,
      нулевой:  dayKalams(d(12), d(12)).length,
      битый:    dayKalams(new Date('нет такой даты'), d(18)).length,
      нормальный: dayKalams(d(6), d(18)).length,
    })
    """, tmp_path)
    assert res == {"обратный": 0, "нулевой": 0, "битый": 0, "нормальный": 3}
