@pytest.mark.parametrize("день", [1, 8, 15, 22, 29])
def test_титхи_не_зависит_от_аянамши(день, swe):
    """Титхи — разность Луна−Солнце, аянамша из неё выпадает тождественно.

    Значит тропический и сидерический расчёты титхи обязаны совпасть бит в бит.
    Если однажды не совпадут — значит одна из долгот считается в другой системе
    отсчёта, чем вторая.
    """
    jd = swe.julday(2026, 7, день, 6.0)
    троп = (pn.moon_lon(jd) - pn.sun_lon(jd)) % 360
    сид = (pn.moon_lon_sid(jd) - pn.sun_lon_sid(jd)) % 360
    assert троп == pytest.approx(сид, abs=1e-9)
    assert int(троп / 12) == tithi_index(jd)


@pytest.mark.parametrize("день", [1, 8, 15, 22, 29])
def test_йога_считается_от_сидерических_долгот(день, swe):
    """Йога — СУММА долгот, и вот в ней аянамша не сокращается.

    Регрессия ловушки из задачи 2.12: тропическая сумма отличается от
    сидерической ровно на 2×аянамша (~47.45° в 2026), то есть на 3.5 йоги.
    Тест требует, чтобы модуль считал именно от сидерических долгот.
    """
    jd = swe.julday(2026, 7, день, 6.0)
    aya = swe.get_ayanamsa_ex_ut(jd, swe.FLG_SWIEPH)[1]

    сумма_сид = (pn.sun_lon_sid(jd) + pn.moon_lon_sid(jd)) % 360
    сумма_троп = (pn.sun_lon(jd) + pn.moon_lon(jd)) % 360

    # Сумма сдвинута ровно на две аянамши — это и есть причина ловушки
    assert (сумма_троп - сумма_сид) % 360 == pytest.approx(2 * aya, abs=1e-6)
    assert yoga_index(jd) == int(сумма_сид / ЙОГА_РАЗМЕР)


def test_тропическая_йога_уехала_бы_почти_на_четыре_позиции(swe):
    """Проверка, что предыдущий тест не бутафория: цена ошибки — 3-4 йоги.

    Если бы разница была в пределах одной йоги, тест выше ловил бы дефект не
    всегда. Здесь фиксируем масштаб: 2×аянамша ≈ 47.5°, а йога 13°20′.
    """
    расхождения = []
    for день in range(1, 29):
        jd = swe.julday(2026, 7, день, 6.0)
        троп_idx = int(((pn.sun_lon(jd) + pn.moon_lon(jd)) % 360) / ЙОГА_РАЗМЕР)
        расхождения.append((троп_idx - yoga_index(jd)) % 27)
    # 2×23.73° = 47.45° = 3.56 йоги → сдвиг всегда 3 или 4 позиции
    assert set(расхождения) <= {3, 4}
    assert all(r != 0 for r in расхождения)


