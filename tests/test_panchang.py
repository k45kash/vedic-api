def test_мухурты_и_хоры_делят_день_поровну():
    """15 дневных мухурт покрывают светлое время, 12 дневных хор — тоже.

    Инвариант деления: длительности внутри половины суток равны между собой.
    """
    res = calc_panchang(date(2026, 7, 25), date(2026, 7, 25), TZ, LAT, LON)
    день = res["days"][0]
    дневные = [m for m in день["muhurtas"] if m["day_night"] == "день"]
    ночные = [m for m in день["muhurtas"] if m["day_night"] == "ночь"]
    assert len(дневные) == len(ночные) == 15
    assert sum(m["duration_h"] for m in дневные) == pytest.approx(день["day_dur_h"], abs=1e-6)
    # 1e-6 ч = 3.6 мс: запас на накопление ошибки в `jd_sunrise + i × шаг`
    for m in дневные[1:]:
        assert m["duration_h"] == pytest.approx(дневные[0]["duration_h"], abs=1e-6)

    хоры_дня = [h for h in день["horas"] if h["day_night"] == "день"]
    assert len(хоры_дня) == 12
    assert sum(h["duration_h"] for h in хоры_дня) == pytest.approx(день["day_dur_h"], abs=1e-6)


def test_хоры_идут_халдейским_порядком():
    """Владелец хоры сменяется по халдейскому ряду, первый — по дню недели.

    Эталон — классическое правило: суббота начинается с Сатурна, воскресенье
    с Солнца и так далее; отсюда же и названия дней недели.
    """
    res = calc_panchang(date(2026, 7, 25), date(2026, 7, 26), TZ, LAT, LON)
    ряд = pn.HORA_PLANETS
    for день in res["days"]:
        первый = день["horas"][0]["planet"]
        ожидаемый = pn.WEEKDAY_FIRST_HORA[день["dt_sunrise"].weekday()]
        assert первый == ожидаемый, день["date"]
        старт = ряд.index(первый)
        assert [h["planet"] for h in день["horas"]] == [
            ряд[(старт + i) % 7] for i in range(24)
        ]


def test_восход_и_закат_согласованы_с_swiss_ephemeris(swe):
    """Восход/закат берутся из `rise_trans`, а не из приближения Meeus.

    Проверяем, что для умеренной широты используется именно точный путь:
    высота Солнца в момент восхода должна быть около −0.833° (рефракция плюс
    полудиаметр диска) — приближение дало бы промах в минуты.
    """
    jd_noon = dt_to_jd(datetime(2026, 7, 25, 12, 0)) - TZ / 24
    jd_rise, jd_set = pn.get_sunrise_sunset(jd_noon, LAT, LON, TZ)
    assert jd_rise < jd_set
